"""Staging support for OpenFE's charge-molecules command."""

from __future__ import annotations

import shlex
from dataclasses import dataclass
from pathlib import Path

DEFAULT_CHARGE_SETTINGS = Path(__file__).with_name("charge_settings.yaml")


@dataclass(frozen=True)
class ChargeMoleculesConfig:
    input_sdf: Path
    output_sdf: Path
    settings_yaml: Path
    n_cores: int = 4
    overwrite_charges: bool = True
    openfe_command: str = "openfe"

    def validate(self) -> None:
        if not self.input_sdf.is_file() or self.input_sdf.suffix.lower() != ".sdf":
            raise ValueError(f"Input must be an existing SDF file: {self.input_sdf}")
        if (
            not self.settings_yaml.is_file()
            or self.settings_yaml.suffix.lower()
            not in {
                ".yaml",
                ".yml",
            }
        ):
            raise ValueError(
                f"Charge settings must be an existing YAML file: {self.settings_yaml}"
            )
        if self.output_sdf.suffix.lower() != ".sdf":
            raise ValueError(f"Output must have an .sdf extension: {self.output_sdf}")
        if self.input_sdf.resolve() == self.output_sdf.resolve():
            raise ValueError("Input and output SDF paths must be different")
        if self.n_cores < 1:
            raise ValueError("Number of charging processes must be at least 1")
        if not self.openfe_command.strip():
            raise ValueError("OpenFE command cannot be empty")

    def command(self) -> list[str]:
        result = [
            self.openfe_command,
            "charge-molecules",
            "-M",
            str(self.input_sdf),
            "-o",
            str(self.output_sdf),
            "-n",
            str(self.n_cores),
            "-s",
            str(self.settings_yaml),
        ]
        if self.overwrite_charges:
            result.append("--overwrite-charges")
        return result

    def render_shell_config(self) -> str:
        values = {
            "OPENFE_COMMAND": self.openfe_command,
            "INPUT_SDF": str(self.input_sdf),
            "OUTPUT_SDF": str(self.output_sdf),
            "N_CORES": self.n_cores,
            "SETTINGS_YAML": str(self.settings_yaml),
            "OVERWRITE_CHARGES": str(self.overwrite_charges).lower(),
        }
        return (
            "\n".join(
                ["# Generated by AlchemForge for OpenFE ligand charging."]
                + [f"{key}={shlex.quote(str(value))}" for key, value in values.items()]
            )
            + "\n"
        )


def stage(config: ChargeMoleculesConfig, task_directory: Path) -> tuple[Path, Path]:
    config.validate()
    task_directory.mkdir(parents=True, exist_ok=True)
    config_path = task_directory / "charge_molecules.conf"
    script_path = task_directory / "charge_molecules.sh"
    config_path.write_text(config.render_shell_config(), encoding="utf-8")
    source_script = Path(__file__).with_name("charge_molecules.sh")
    script_path.write_text(source_script.read_text(encoding="utf-8"), encoding="utf-8")
    script_path.chmod(script_path.stat().st_mode | 0o100)
    return script_path, config_path
