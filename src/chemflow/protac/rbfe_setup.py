"""Bridge the linker designer's output into an AlchemForge RBFE project.

The linker designer exports ``protac_poses.sdf`` — the top PROTACs already posed
in 3D in the ternary-complex frame — which is exactly the congeneric set a
relative binding free energy (RBFE) run needs. AlchemForge's ligand-RBFE expects
a single ``library_sdf`` whose records each carry a unique name, plus a receptor
PDB. This module re-titles the SDF records (so each ``_Name`` is unique) and
writes a ready-to-edit RBFE TOML pointing at the receptor and the prepared SDF.

Pure text processing (no RDKit), so it can run anywhere and is easy to test. The
heavy RBFE then runs under AlchemForge::

    chemflow protac rbfe-setup --poses protac_poses.sdf --receptor ternary.pdb --out rbfe_project
    alchemforge rbfe all rbfe_project/rbfe.toml      # fix-pdb -> charge -> plan -> stage+SLURM
"""

from __future__ import annotations

import re
from pathlib import Path

_ID_TAG = re.compile(r">\s*<id>\s*\n\s*(\S+)", re.IGNORECASE)

_RBFE_TOML = """\
# AlchemForge ligand-RBFE configuration (generated by chemflow protac rbfe-setup)
# Review the paths/values, then:  alchemforge ligand-rbfe validate {toml_name}
# or run the whole prep chain:    alchemforge rbfe all {toml_name}

[project]
name = "{name}"
work_dir = "work"

[system]
protein = "{protein}"              # receptor / ternary complex PDB
force_field = "amber99sb-star-ildn-mut"
water_model = "tip3p"
gromacs_command = "gmx"
box_shape = "dodecahedron"
box_distance = 1.2
neutralize = true
ion_concentration = 0.15

[ligands]
library_sdf = "{library_sdf}"     # the posed PROTACs, one record per candidate (unique names)

[mapping]
network_method = "minimal_spanning"   # lomap | minimal_spanning | minimal_redundant | radial
atom_mapper = "lomap"                  # lomap | kartograf
element_change = false
max3d_angstrom = 10.0
require_cycle_covering = true

[topology]
backend = "pmx"
charge_method = "bcc"                   # bcc | user
charge_change_method = "reject"         # reject | correction

[simulation]
replicates = 3
lambda_windows = 21
timestep_ps = 0.002
equilibration_ns = 1.0
production_ns = 5.0
sampling_method = "independent"         # independent | hrex

[slurm]
partition = "gpu"
nodes = 1
cpus_per_task = 8
gpus = 1
memory = "16G"
walltime = "24:00:00"
"""


def _split_sdf_records(text: str) -> list[str]:
    records = []
    for chunk in text.split("$$$$"):
        if chunk.strip():
            records.append(chunk.lstrip("\n"))
    return records


def retitle_sdf(sdf_text: str) -> tuple[str, list[str]]:
    """Set each SDF record's title line to its ``<id>`` tag (or a serial name).

    Returns ``(new_sdf_text, names)``. A unique title is what AlchemForge reads as
    the ligand ``_Name``; records without an ``id`` tag get ``ligandNNNN``.
    """
    out_records: list[str] = []
    names: list[str] = []
    used: set[str] = set()
    for i, record in enumerate(_split_sdf_records(sdf_text), start=1):
        match = _ID_TAG.search(record)
        name = match.group(1) if match else f"ligand{i:04d}"
        base, n = name, 1
        while name in used:                       # guarantee uniqueness
            name = f"{base}_{n}"
            n += 1
        used.add(name)
        names.append(name)

        lines = record.split("\n")
        lines[0] = name                           # molblock title line == _Name
        out_records.append("\n".join(lines).rstrip("\n") + "\n$$$$\n")
    return "".join(out_records), names


def prepare_rbfe(
    poses_sdf: str | Path,
    receptor_pdb: str | Path,
    out_dir: str | Path,
    *,
    name: str = "protac_rbfe",
) -> dict[str, object]:
    """Create an RBFE project folder from the designer's posed PROTAC SDF.

    Writes ``<out_dir>/ligands.sdf`` (uniquely named records) and
    ``<out_dir>/rbfe.toml``. Returns the written paths and the ligand names.
    """
    poses = Path(poses_sdf).expanduser().resolve()
    receptor = Path(receptor_pdb).expanduser().resolve()
    out = Path(out_dir).expanduser().resolve()
    if not poses.is_file():
        raise FileNotFoundError(f"poses SDF not found: {poses}")
    if not receptor.is_file():
        raise FileNotFoundError(f"receptor PDB not found: {receptor}")
    out.mkdir(parents=True, exist_ok=True)

    sdf_text, names = retitle_sdf(poses.read_text(encoding="utf-8", errors="replace"))
    if not names:
        raise ValueError(f"no molecules found in {poses}")

    library = out / "ligands.sdf"
    library.write_text(sdf_text, encoding="utf-8")
    toml_path = out / "rbfe.toml"
    toml_path.write_text(
        _RBFE_TOML.format(name=name, protein=receptor, library_sdf=library.name,
                          toml_name=toml_path.name),
        encoding="utf-8",
    )
    return {"toml": toml_path, "ligands": library, "names": names, "n": len(names)}
